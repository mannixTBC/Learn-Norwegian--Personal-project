import { build } from 'vite';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
import React from 'react';
import TestRenderer, { act } from 'react-test-renderer';
const outDir = resolve('node_modules/.cache/dialogue-walkthrough-test');
await build({logLevel:'error', plugins:[{name:'mock-speech',enforce:'pre',resolveId(id){if(id.endsWith('/norwegianSpeech'))return 'virtual:speech';},load(id){if(id==='virtual:speech')return `export const speakNorwegian = (text, options) => { options.onPlaybackStart?.(); globalThis.calls.push({text, options}); return new Promise(resolve => { globalThis.finishAudio = resolve; options.signal.addEventListener('abort', () => resolve({cancelled:true}), {once:true}); }); };`;}}],build:{ssr:true,outDir,emptyOutDir:false,rollupOptions:{input:resolve('src/modules/lessons/norwegian-program/DialogueWalkthrough.js'),output:{entryFileNames:'walkthrough.mjs'}}}});
const {default: Component}=await import(pathToFileURL(resolve(outDir,'walkthrough.mjs')));
const saved=new Map(); globalThis.localStorage={getItem:k=>saved.get(k),setItem:(k,v)=>saved.set(k,v)}; globalThis.calls=[];
const dialogue=[['Anna','Hei','Salut'],['Lars','Hei igjen','Salut din nou'],['Anna','Takk','Mersi']];
let renderer;
await act(async()=>{renderer=TestRenderer.create(React.createElement(Component,{dialogue},React.createElement('p',null,'Practice')));});
const button = label => renderer.root.findAllByType('button').find(b=>b.props.children===label || b.props['aria-label']===label);
assert.equal(calls.length,1);
assert.equal(calls[0].text,'Hei'); assert.equal(renderer.root.findAllByType('article').length,2);
await act(async()=>button('Oprește sunetul').props.onClick());
assert.equal(calls[0].options.signal.aborted,true); assert.equal(saved.get('nordlingo-dialogue-muted'),'true');
await act(async()=>button('Mai departe').props.onClick());
assert.equal(calls.length,1); assert.equal(renderer.root.findAllByType('article').length,1);
await act(async()=>button('Activează sunetul').props.onClick());
assert.equal(calls[1].text,'Takk');
await act(async()=>button('În română').props.onClick());
assert.equal(calls[1].options.signal.aborted,true);
assert.equal(button('Înapoi'), undefined);
assert.equal(button('Exersează în text'), undefined);
await act(async()=>button('Reascultă scena').props.onClick());
await act(async()=>renderer.unmount());
assert.equal(calls[2].options.signal.aborted,true);
// Pair playback stops after two lines, without advancing the scene.
await act(async()=>{renderer=TestRenderer.create(React.createElement(Component,{dialogue}));});
await act(async()=>{finishAudio({ok:true}); await new Promise(r=>setTimeout(r,500));});
assert.equal(calls.at(-1).text,'Hei igjen');
await act(async()=>finishAudio({ok:true}));
assert.equal(renderer.root.findAllByType('article').length,2);
assert.ok(button('Mai departe'));
await act(async()=>renderer.unmount());
// A saved mute preference keeps the dialogue visible without autoplay.
saved.set('nordlingo-dialogue-muted', 'true');
const beforeMutedMount = calls.length;
await act(async()=>{renderer=TestRenderer.create(React.createElement(Component,{dialogue}));});
assert.equal(calls.length, beforeMutedMount);
assert.equal(renderer.root.findAllByType('article').length, 2);
await act(async()=>renderer.unmount());
console.log('PASS: automatic start, paired playback, manual advance, mute persistence, translation stop, replay and unmount cancellation.');
