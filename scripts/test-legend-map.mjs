import { build } from 'vite';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
import React from 'react';
import TestRenderer, { act } from 'react-test-renderer';
import { MemoryRouter } from 'react-router-dom';
const out=resolve('node_modules/.cache/legend-map-tests');
await build({logLevel:'error',plugins:[{name:'legend-services',enforce:'pre',resolveId(id){if(id.endsWith('/learningActivity'))return 'virtual:study';if(id.endsWith('/AuthContext'))return 'virtual:auth';},load(id){if(id==='virtual:study')return 'export const getStudySummary=()=>({streak:0});';if(id==='virtual:auth')return 'export const useAuth=()=>({user:null});';}}],build:{ssr:true,outDir:out,emptyOutDir:true,rollupOptions:{input:resolve('src/modules/exercises/GamesMosaic.js'),output:{entryFileNames:'legend.mjs'}}}});
const {default:Game}=await import(pathToFileURL(resolve(out,'legend.mjs')));
globalThis.requestAnimationFrame=fn=>fn();
globalThis.localStorage={getItem:()=>null,setItem:()=>{}};
const cards=['pronunciation','quiz','order','verbs','word','review'].map(id=>({id,title:id,to:'/'+id,progress:{completed:0,target:5}}));
const state={version:1,coins:740,earnedCoins:1240,sessions:3,completedStops:['port','far','fiord'],stageSessionBaseline:3,processedIds:[]};
const base={level:'A1',cards,activities:[{id:'listen',to:'/asculta',progress:{best:0,sessions:0}}],reviewStats:{due:0},expedition:state};
let calls=0,view;
const mount=async props=>act(async()=>{view=TestRenderer.create(React.createElement(MemoryRouter,null,React.createElement(Game,{...base,...props})));});
const text=node=>node.children.map(c=>typeof c==='string'?c:text(c)).join('');
await mount({onClaimStop:()=>{calls++;}});
const grid=view.root.findByProps({className:'practice-rows'});
assert.deepEqual(grid.findAll(node=>node.type==='a').map(node=>node.props['data-game']),['quiz','verbs','word','listen','order','pronunciation'],'grouped vocabulary and quick practice links');
assert.ok(view.root.findAll(node=>node.type==='a').some(node=>node.props.href==='/scenarii?nivel=A1'));
const summary=view.root.findByProps({className:'legend-next'});
assert.equal(summary.findAllByType('button').length,0,'summary is informational only');
assert.ok(text(summary).includes('260'),'real cost 1000 less balance 740');
const current=view.root.findAllByType('button').find(n=>(n.props.className||'').includes('npass-map__stop--current'));
assert.equal(current.findAllByType('svg').length,1,'current obstacle displays a lock');
await act(async()=>current.props.onClick());
let unlock=view.root.findAllByType('button').find(n=>text(n).startsWith('Deblochează'));
assert.equal(unlock.props.disabled,true,'insufficient funds prevent unlock');
assert.equal(calls,0);
await act(async()=>view.unmount());
await mount({expedition:{...state,coins:3400,sessions:8},onClaimStop:id=>{calls++;assert.equal(id,'pod');return {claimed:false,reason:'storage-unavailable'};}});
await act(async()=>view.root.findAllByType('button').find(n=>(n.props.className||'').includes('npass-map__stop--current')).props.onClick());
unlock=view.root.findAllByType('button').find(n=>text(n).startsWith('Deblochează'));
assert.equal(unlock.props.disabled,false);
await act(async()=>unlock.props.onClick());
assert.equal(calls,1,'unlock is routed through existing progression service');
assert.ok(view.root.findByProps({className:'legend-lock-panel'}));
await act(async()=>view.unmount());
console.log('PASS: lock interaction, real coin shortfall, summary without CTA, blocked and eligible unlock.');
