import {build} from 'vite';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
import React from 'react';
import TestRenderer,{act} from 'react-test-renderer';
const out=resolve('node_modules/.cache/lesson-dialogue-overview');
await build({logLevel:'error',plugins:[{name:'speech',enforce:'pre',resolveId:id=>id.endsWith('/norwegianSpeech')?'virtual:speech':null,load:id=>id==='virtual:speech'?'export const speakNorwegian=(...args)=>globalThis.dialogueSpeech(...args);':null}],build:{ssr:true,outDir:out,emptyOutDir:true,rollupOptions:{input:resolve('src/modules/lessons/norwegian-program/LessonDialogueOverview.js'),output:{entryFileNames:'view.mjs'}}}});
const {default:View}=await import(pathToFileURL(resolve(out,'view.mjs')));
const dialogue=[['Anna','Hei!','Salut!'],['Lars','God dag!','Bună ziua!'],['Anna','Takk!','Mulțumesc!']];
let calls=[],r;
globalThis.dialogueSpeech=async(text,options)=>{calls.push({text,options});return {ok:true};};
await act(async()=>{r=TestRenderer.create(React.createElement(View,{dialogue}));});
const button=text=>r.root.findAllByType('button').find(b=>b.props.children===text);
assert.equal(r.root.findAllByType('article').length,3);
assert.equal(calls.length,0,'audio must be requested by the user');
await act(async()=>button('Ascultă dialogul').props.onClick());
assert.deepEqual(calls.map(c=>c.text),dialogue.map(d=>d[1]));
assert.deepEqual(calls.map(c=>c.options.voice),['female','male','female']);
await act(async()=>button('În română').props.onClick());
assert.equal(r.root.findAllByProps({lang:'ro'}).length,3);
globalThis.dialogueSpeech=async()=>({ok:false});
await act(async()=>button('Ascultă dialogul').props.onClick());
assert.equal(r.root.findAllByProps({role:'alert'}).length,1);
let signal;
globalThis.dialogueSpeech=(text,options)=>{signal=options.signal;return new Promise(resolve=>signal.addEventListener('abort',()=>resolve({cancelled:true}),{once:true}));};
await act(async()=>{void button('Ascultă dialogul').props.onClick();});
await act(async()=>button('Oprește audio').props.onClick());
assert.equal(signal.aborted,true);
await act(async()=>{void button('Ascultă dialogul').props.onClick();});
await act(async()=>r.unmount());
assert.equal(signal.aborted,true);
console.log('PASS: complete visible dialogue, ordered voices, translations, audio failure, stop and navigation cancellation.');
