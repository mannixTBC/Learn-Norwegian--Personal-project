import { build } from 'vite';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { existsSync } from 'node:fs';
import assert from 'node:assert/strict';
import React from 'react';
import TestRenderer, { act } from 'react-test-renderer';
const root = resolve(import.meta.dirname, '..');
const output = resolve(root, 'node_modules/.cache/sentence-tests');
await build({ configFile: resolve(root, 'vite.config.js'), logLevel: 'error', build: { ssr: true, outDir: output, rollupOptions: { input: { ui: resolve(root, 'src/modules/exercises/SentenceWorkshop.js'), catalog: resolve(root, 'src/modules/exercises/learningImageCatalog.js') }, output: { entryFileNames: '[name].mjs' } } } });
const { default: Workshop } = await import(pathToFileURL(resolve(output, 'ui.mjs')));
const { learningImageCatalog, selectLearningImageId, getLearningImage } = await import(pathToFileURL(resolve(output, 'catalog.mjs')));
assert.equal(learningImageCatalog.length, 120);
for (const image of learningImageCatalog) assert.ok(existsSync(resolve(root, 'public' + image.src)));
assert.equal(selectLearningImageId('Jeg drikker kaffe om morgenen.'), 'illustrated-drinks-kaffe');
assert.equal(selectLearningImageId('kaffemaskinen'), null);
assert.equal(selectLearningImageId('kaffe og te'), null);
assert.equal(selectLearningImageId('Jeg heter Nora'), null);
assert.equal(getLearningImage('missing'), null);
let tree, selected = [], checked = false, next = 0, spoken = 0;
const question = { id: 'coffee', prompt: 'Eu beau cafea dimineața.', answer: 'Jeg drikker kaffe', words: ['kaffe', 'Jeg', 'drikker'], imageId: selectLearningImageId('kaffe') };
const render = () => React.createElement(Workshop, { question, level: 'A1', current: 0, total: 5, selected, checked, correct: true, completeAnswer: selected.length === 3, setSelected: update => { selected = typeof update === 'function' ? update(selected) : update; tree.update(render()); }, onVerify: () => { checked = true; tree.update(render()); }, onNext: () => next++, onSpeak: () => spoken++, onExit() {} });
act(() => { tree = TestRenderer.create(render()); });
const click = text => act(() => tree.root.findAllByType('button').find(button => button.children.join('') === text).props.onClick());
assert.equal(tree.root.findAllByType('button').find(button => button.children.join('') === 'Verifică').props.disabled, true);
click('Jeg'); click('drikker'); click('kaffe'); assert.deepEqual(selected, [1, 2, 0]);
act(() => tree.root.findAllByType('button').find(button => button.props['aria-label']?.startsWith('Scoate drikker')).props.onClick());
assert.deepEqual(selected, [1, 0]); click('↻ Reia'); assert.deepEqual(selected, []);
click('Jeg'); click('drikker'); click('kaffe'); click('Verifică'); click('♫ Ascultă propoziția'); click('Continuă →');
assert.equal(spoken, 1); assert.equal(next, 1);
act(() => tree.root.findAllByType('img').find(image => image.props.src.includes('drinks.webp')).props.onError());
assert.equal(tree.root.findAllByProps({ className: 'sw-art' }).length, 0);
act(() => tree.unmount());
console.log('Sentence workshop: artwork integrity, conservative matching, ordering, removal, reset, verification, audio, continuation and broken-image fallback passed.');
